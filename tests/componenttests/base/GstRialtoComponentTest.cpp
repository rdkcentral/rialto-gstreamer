uint32_t GstRialtoComponentTest::sendNeedData(int32_t sourceId, size_t frameCount)
{
    auto shmInfo = std::make_shared<firebolt::rialto::MediaPlayerShmInfo>();
    shmInfo->maxMetadataBytes = kMaxMetadataBytes;
    shmInfo->metadataOffset = kMetadataOffset;
    shmInfo->mediaDataOffset = kMediaDataOffset;
    shmInfo->maxMediaBytes = kMaxMediaBytes;
    const uint32_t kRequestId{++m_needDataRequestId};
    m_serverStub->notifyNeedMediaDataEvent(kSessionId, sourceId, frameCount, kRequestId, shmInfo);
    return kRequestId;
}

bool GstRialtoComponentTest::waitForServerCall(const std::string &method, unsigned count)
{
    std::unique_lock<std::mutex> lock{m_callsMutex};
    return m_callsCond.wait_for(lock, kTimeout, [&]() { return m_calls[method] >= count; });
}

bool GstRialtoComponentTest::waitForHaveData(uint32_t requestId, HaveDataCall &result)
{
    std::unique_lock<std::mutex> lock{m_callsMutex};
    auto findCall = [&]()
    {
        for (const auto &call : m_haveDataCalls)
        {
            if (call.requestId == requestId)
            {
                result = call;
                return true;
            }
        }
        return false;
    };
    return m_callsCond.wait_for(lock, kTimeout, findCall);
}

std::vector<GstRialtoComponentTest::ShmFrame> GstRialtoComponentTest::readFramesFromShm(uint32_t numFrames) const
{
    // Metadata V2: each frame is [uint32 metadata size, little endian][MediaSegmentMetadata][media data]
    std::vector<ShmFrame> frames;
    uint32_t offset{kMediaDataOffset};
    for (uint32_t i = 0; i < numFrames; ++i)
    {
        const uint8_t *position{m_shmAddress + offset};
        const uint32_t kMetadataSize{static_cast<uint32_t>(position[0]) | (static_cast<uint32_t>(position[1]) << 8) |
                                     (static_cast<uint32_t>(position[2]) << 16) |
                                     (static_cast<uint32_t>(position[3]) << 24)};
        offset += sizeof(uint32_t);
        ShmFrame frame;
        if (offset + kMetadataSize > kMediaDataOffset + kMaxMediaBytes ||
            !frame.metadata.ParseFromArray(m_shmAddress + offset, kMetadataSize))
        {
            ADD_FAILURE() << "Could not parse the metadata of frame " << i << " in the shared memory";
            break;
        }
        offset += kMetadataSize;
        if (offset + frame.metadata.length() > kMediaDataOffset + kMaxMediaBytes)
        {
            ADD_FAILURE() << "Frame " << i << " does not fit in the media data partition";
            break;
        }
        frame.data.assign(m_shmAddress + offset, m_shmAddress + offset + frame.metadata.length());
        offset += frame.metadata.length();
        frames.push_back(std::move(frame));
    }
    return frames;
}

void GstRialtoComponentTest::createAudioPipeline(const char *caps)
{
    m_pipeline = gst_pipeline_new("rialto-ct-pipeline");
    // appsrc is created from its type, so the test does not depend on the GStreamer plugin registry
    m_appSrc = GST_ELEMENT(g_object_new(GST_TYPE_APP_SRC, "name", "src", nullptr));
    m_sink = gst_element_factory_make("rialtomseaudiosink", "sink");
    ASSERT_NE(m_pipeline, nullptr);
    ASSERT_NE(m_appSrc, nullptr);
    ASSERT_NE(m_sink, nullptr) << "rialtomseaudiosink is not registered";

    GstCaps *appSrcCaps = gst_caps_from_string(caps);
    ASSERT_NE(appSrcCaps, nullptr);
    g_object_set(G_OBJECT(m_appSrc), "caps", appSrcCaps, "format", GST_FORMAT_TIME, nullptr);
    gst_caps_unref(appSrcCaps);

    // Audio only, clear content; enable-last-sample lets the test see when buffers reached the sink
    g_object_set(G_OBJECT(m_sink), "single-path-stream", TRUE, "has-drm", FALSE, "enable-last-sample", TRUE, nullptr);

    gst_bin_add_many(GST_BIN(m_pipeline), m_appSrc, m_sink, nullptr);
    ASSERT_TRUE(gst_element_link(m_appSrc, m_sink));
}

GstStateChangeReturn GstRialtoComponentTest::startPlaying()
{
    // NULL->READY blocks until the client is RUNNING: the simulated server reports RUNNING once the client registered
    std::thread runningSender{[this]()
                              {
                                  if (waitForServerCall("registerClient"))
                                  {
                                      sendApplicationStateRunning();
                                  }
                              }};
    const GstStateChangeReturn kResult{gst_element_set_state(m_pipeline, GST_STATE_PLAYING)};
    runningSender.join();
    return kResult;
}

void GstRialtoComponentTest::pushAudioBuffers(unsigned count, size_t size, GstClockTime duration)
{
    for (unsigned i = 0; i < count; ++i)
    {
        GstBuffer *buffer = gst_buffer_new_allocate(nullptr, size, nullptr);
        gst_buffer_memset(buffer, 0, static_cast<guint8>(i + 1), size); // frame i is filled with the value i + 1
        GST_BUFFER_PTS(buffer) = i * duration;
        GST_BUFFER_DURATION(buffer) = duration;
        ASSERT_EQ(gst_app_src_push_buffer(GST_APP_SRC(m_appSrc), buffer), GST_FLOW_OK);
    }
}

bool GstRialtoComponentTest::waitForQueuedInSink(GstClockTime lastPts)
{
    const auto kEnd{std::chrono::steady_clock::now() + kTimeout};
    while (std::chrono::steady_clock::now() < kEnd)
    {
        GstSample *sample{nullptr};
        g_object_get(G_OBJECT(m_sink), "last-sample", &sample, nullptr);
        if (sample)
        {
            GstBuffer *buffer = gst_sample_get_buffer(sample);
            const bool kQueued{buffer && GST_BUFFER_PTS(buffer) == lastPts};
            gst_sample_unref(sample);
            if (kQueued)
            {
                return true;
            }
        }
        std::this_thread::sleep_for(std::chrono::milliseconds{10});
    }
    return false;
}

bool GstRialtoComponentTest::waitForPipelineState(GstState state)
{
    GstState current{GST_STATE_VOID_PENDING};
    const GstStateChangeReturn kResult{
        gst_element_get_state(m_pipeline, &current, nullptr,
                              std::chrono::duration_cast<std::chrono::nanoseconds>(kTimeout).count())};
    return kResult == GST_STATE_CHANGE_SUCCESS && current == state;
}

GstMessage *GstRialtoComponentTest::waitForBusMessage(GstMessageType types)
{
    GstBus *bus = gst_element_get_bus(m_pipeline);
    GstMessage *message = gst_bus_timed_pop_filtered(bus,
                                                     std::chrono::duration_cast<std::chrono::nanoseconds>(kTimeout)
                                                         .count(),
                                                     types);
    gst_object_unref(bus);
    return message;
}

void GstRialtoComponentTest::stopPipeline()
{
    if (m_pipeline)
    {
        // The server stub is still running, so removeSource, stop and destroySession are answered
        gst_element_set_state(m_pipeline, GST_STATE_NULL);
        gst_object_unref(m_pipeline);
        m_pipeline = nullptr;
        m_appSrc = nullptr;
        m_sink = nullptr;
    }
}

void GstRialtoComponentTest::waitForClientDisconnected()
{
    // RialtoClient keeps one connection and one application state per process. Before the next test starts its
    // own server stub, wait until the client has seen this server going away (state UNKNOWN), so that it
    // registers again - like stopApplication() in the Rialto client component tests.
    auto observer = std::make_shared<ApplicationStateObserver>();
    auto unknownReceived = observer->unknownReceived();
    std::shared_ptr<firebolt::rialto::IControl> control{
        firebolt::rialto::IControlFactory::createFactory()->createControl()};
    firebolt::rialto::ApplicationState state{firebolt::rialto::ApplicationState::UNKNOWN};
    const bool kRegistered{control && control->registerClient(observer, state)};

    m_serverStub.reset();

    if (kRegistered && firebolt::rialto::ApplicationState::UNKNOWN != state)
    {
        EXPECT_EQ(unknownReceived.wait_for(kTimeout), std::future_status::ready)
            << "RialtoClient did not notice the server disconnection";
    }
    control.reset();
}

void GstRialtoComponentTest::initSharedMemory()
{
    m_shmFd = static_cast<int>(syscall(SYS_memfd_create, "rialto_gst_ct_shm", MFD_CLOEXEC));
    ASSERT_GE(m_shmFd, 0);
    ASSERT_EQ(ftruncate(m_shmFd, static_cast<off_t>(kShmSize)), 0);
    void *address = mmap(nullptr, kShmSize, PROT_READ | PROT_WRITE, MAP_SHARED, m_shmFd, 0);
    ASSERT_NE(address, MAP_FAILED);
    m_shmAddress = static_cast<uint8_t *>(address);
}

void GstRialtoComponentTest::termSharedMemory()
{
    if (m_shmAddress)
    {
        munmap(m_shmAddress, kShmSize);
        m_shmAddress = nullptr;
    }
    if (m_shmFd >= 0)
    {
        close(m_shmFd);
        m_shmFd = -1;
    }
}
