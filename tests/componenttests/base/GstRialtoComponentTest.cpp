    // Capabilities (asked once, when the sink classes are created)
    RESPOND_BY_DEFAULT(m_mediaCapabilitiesModuleMock, getSupportedAudioCapabilities);
    RESPOND_BY_DEFAULT(m_mediaCapabilitiesModuleMock, getSupportedVideoCapabilities);
    ON_CALL(*m_mediaPipelineCapabilitiesModuleMock, getSupportedMimeTypes(_, _, _, _))
        .WillByDefault(Invoke(
            [this](::google::protobuf::RpcController *, const firebolt::rialto::GetSupportedMimeTypesRequest *request,
                   firebolt::rialto::GetSupportedMimeTypesResponse *response, ::google::protobuf::Closure *done)
            {
                const auto &mimeTypes{request->media_type() == firebolt::rialto::ProtoMediaSourceType::VIDEO
                                          ? kSupportedVideoMimeTypes
                                          : request->media_type() == firebolt::rialto::ProtoMediaSourceType::AUDIO
                                                ? kSupportedAudioMimeTypes
                                                : std::vector<std::string>{}};
                for (const auto &mimeType : mimeTypes)
                {
                    response->add_mime_types(mimeType);
                }
                done->Run();
                recordCall("getSupportedMimeTypes");
            }));
    RESPOND_BY_DEFAULT(m_mediaPipelineCapabilitiesModuleMock, isMimeTypeSupported);
    RESPOND_BY_DEFAULT(m_mediaPipelineCapabilitiesModuleMock, getSupportedProperties);
    RESPOND_BY_DEFAULT(m_mediaPipelineCapabilitiesModuleMock, isVideoMaster);

